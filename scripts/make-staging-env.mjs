#!/usr/bin/env node
/**
 * Writes .env pointing the app at a STAGING Supabase project.
 *
 * Guards, because .env decides which database the whole app talks to:
 *   1. The project name must look like staging (/staging/i) — a prod ref is
 *      refused outright, so a typo can't silently point the app at prod.
 *   2. Only the anon / publishable key is ever written. The service_role /
 *      secret key is never emitted: anything VITE_-prefixed is inlined into
 *      the browser bundle, so a secret key there is a full data breach.
 *   3. .env must be gitignored before we write it.
 *   4. An existing .env is never clobbered without --force.
 *
 * Run:  node scripts/make-staging-env.mjs --ref <staging-project-ref>
 *       node scripts/make-staging-env.mjs --ref <ref> --force
 */
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs'

const args = process.argv.slice(2)
const ref = args[args.indexOf('--ref') + 1]
const force = args.includes('--force')
const allowName = args.includes('--allow-name-mismatch')

const die = msg => {
  console.error(`\n  ERROR  ${msg}\n`)
  process.exit(1)
}

if (!args.includes('--ref') || !ref || ref.startsWith('--')) {
  die('missing --ref <staging-project-ref>   (find it with: supabase projects list)')
}
if (!/^[a-z]{20}$/.test(ref)) {
  die(`"${ref}" is not a project ref. Refs are exactly 20 lowercase letters.`)
}

// `supabase` may be on PATH as supabase.exe (Windows) or supabase (posix).
const cli = (...a) => {
  try {
    return execFileSync('supabase', a, { encoding: 'utf8', shell: process.platform === 'win32' })
  } catch (e) {
    die(`\`supabase ${a.join(' ')}\` failed — are you logged in?\n         ${String(e.stderr || e.message).trim()}`)
  }
}

// ---- 1. resolve the project and refuse anything that isn't staging ---------
const projects = JSON.parse(cli('projects', 'list', '-o', 'json'))
const project = projects.find(p => (p.id || p.ref) === ref)
if (!project) die(`ref ${ref} is not in your project list. Wrong account, or wrong ref?`)

const name = project.name || '(unnamed)'
if (!/staging/i.test(name) && !allowName) {
  die(
    `refusing to write .env — project "${name}" (${ref}) does not look like staging.\n` +
      `         If this really is your staging project, re-run with --allow-name-mismatch.`
  )
}

// ---- 2. take ONLY the anon / publishable key ------------------------------
const keys = JSON.parse(cli('projects', 'api-keys', '--project-ref', ref, '-o', 'json'))
const anon = keys.find(k => k.name === 'anon') || keys.find(k => String(k.api_key || '').startsWith('sb_publishable_'))
if (!anon) die('no anon / publishable key returned for this project.')

const anonKey = anon.api_key || anon.apiKey
if (!anonKey) die('anon key came back empty.')
if (/service_role|sb_secret_/.test(anonKey) || anon.name === 'service_role') {
  die('resolved key is a SECRET key — refusing to write it into a VITE_ variable.')
}

// ---- 3. .env must be gitignored -------------------------------------------
try {
  execFileSync('git', ['check-ignore', '-q', '.env'], { stdio: 'ignore' })
} catch {
  die('.env is NOT gitignored. Fix .gitignore before writing credentials there.')
}

// ---- 4. don't clobber ------------------------------------------------------
if (existsSync('.env') && !force) {
  const cur = readFileSync('.env', 'utf8')
  const curUrl = (cur.match(/^VITE_SUPABASE_URL=(.*)$/m) || [])[1]
  die(`.env already exists (currently ${curUrl || 'unset'}). Re-run with --force to overwrite.`)
}
if (existsSync('.env')) copyFileSync('.env', '.env.bak')

const url = `https://${ref}.supabase.co`
writeFileSync(
  '.env',
  `# STAGING — ${name} (${ref})\n` +
    `# Generated by scripts/make-staging-env.mjs. Never point this at production.\n` +
    `VITE_SUPABASE_URL=${url}\n` +
    `VITE_SUPABASE_ANON_KEY=${anonKey}\n`
)

console.log(`\n  .env written -> ${name} (${ref})`)
console.log(`  VITE_SUPABASE_URL=${url}`)
console.log(`  VITE_SUPABASE_ANON_KEY=${anonKey.slice(0, 12)}…${anonKey.slice(-4)} (${anon.name})`)
if (existsSync('.env.bak')) console.log('  previous .env saved as .env.bak')
console.log('  restart `npm run dev` to pick it up.\n')
